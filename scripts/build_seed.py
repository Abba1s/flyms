"""Build supabase/seed.sql from the CSVs in supabase/seed/.

IDs are deterministic (UUIDv5 of entity + slug), so re-running the seed keeps
links stable. Usage: python3 -I scripts/build_seed.py
"""
import csv
import sys
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SEED_DIR = ROOT / "supabase" / "seed"
OUT = ROOT / "supabase" / "seed.sql"
NAMESPACE = uuid.UUID("6f1c2a52-6a8e-4c3e-9d0b-0f1a7e5b9c11")


def uid(kind, slug):
    return str(uuid.uuid5(NAMESPACE, f"{kind}:{slug}"))


def rows(name):
    path = SEED_DIR / name
    if not path.exists():
        return []
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def lit(value, cast=None):
    if value is None or value == "":
        return "null"
    text = "'" + str(value).replace("'", "''") + "'"
    return f"{text}::{cast}" if cast else text


def insert(table, columns, values):
    if not values:
        return ""
    body = ",\n".join("  (" + ", ".join(v) + ")" for v in values)
    return f"insert into public.{table} ({', '.join(columns)}) values\n{body};\n\n"


def main():
    errors = []
    fields = rows("fields.csv")
    field_ids = {f["slug"]: uid("field", f["slug"]) for f in fields}
    specs = rows("specializations.csv")
    spec_ids = {s["slug"]: uid("specialization", s["slug"]) for s in specs}
    unis = rows("universities.csv")
    uni_ids = {u["slug"]: uid("university", u["slug"]) for u in unis}
    programs = rows("programs.csv")
    program_ids = {p["slug"]: uid("program", p["slug"]) for p in programs}

    sql = ["-- Generated by scripts/build_seed.py — edit the CSVs in supabase/seed/, not this file.\n\n"]
    sql.append(insert("fields", ["id", "slug", "name", "isced_code", "icon", "color", "sop_template", "sort_order"], [
        [lit(field_ids[f["slug"]]), lit(f["slug"]), lit(f["name"]), lit(f["isced_code"]), lit(f["icon"]),
         lit(f["color"]), lit(f["sop_template"]), f["sort_order"]] for f in fields]))

    spec_values = []
    for s in specs:
        if s["field_slug"] not in field_ids:
            errors.append(f"specialization {s['slug']}: unknown field {s['field_slug']}")
            continue
        spec_values.append([lit(spec_ids[s["slug"]]), lit(field_ids[s["field_slug"]]), lit(s["slug"]),
                            lit(s["name"]), s["sort_order"]])
    sql.append(insert("specializations", ["id", "field_id", "slug", "name", "sort_order"], spec_values))

    sql.append(insert("universities", ["id", "slug", "name", "type", "city", "state", "lat", "lng", "qs_ranking",
                                       "qs_ranking_sort"], [
        [lit(uni_ids[u["slug"]]), lit(u["slug"]), lit(u["name"]), lit(u["type"]), lit(u["city"]), lit(u["state"]),
         u["lat"], u["lng"], lit(u["qs_ranking"]), u["qs_ranking_sort"] or "null"] for u in unis]))

    program_cols = ["id", "slug", "university_id", "field_id", "name", "degree_type", "teaching_language",
                    "official_url", "application_url", "application_portal", "tuition_fee_eur",
                    "application_fee_eur", "ielts_min", "english_note", "moi_accepted", "vpd_required",
                    "nc_restricted", "entrance_exam_interview", "state", "last_verified_at", "source_url"]
    program_values, link_values = [], []
    for p in programs:
        if p["university_slug"] not in uni_ids:
            errors.append(f"program {p['slug']}: unknown university {p['university_slug']}")
            continue
        if p["field_slug"] not in field_ids:
            errors.append(f"program {p['slug']}: unknown field {p['field_slug']}")
            continue
        pid = program_ids[p["slug"]]
        program_values.append([
            lit(pid), lit(p["slug"]), lit(uni_ids[p["university_slug"]]), lit(field_ids[p["field_slug"]]),
            lit(p["name"]), lit(p["degree_type"]), lit(p["teaching_language"]), lit(p["official_url"]),
            lit(p["application_url"]), lit(p["application_portal"]), p["tuition_fee_eur"] or "null",
            p["application_fee_eur"] or "null", p["ielts_min"] or "null", lit(p["english_note"]),
            p["moi_accepted"] or "null", p["vpd_required"] or "null", p["nc_restricted"] or "null",
            lit(p["entrance_exam_interview"]), lit(p["state"]), lit(p["last_verified_at"], "date"),
            lit(p["source_url"]),
        ])
        for slug in filter(None, p["specialization_slugs"].split("|")):
            if slug not in spec_ids:
                errors.append(f"program {p['slug']}: unknown specialization {slug}")
                continue
            link_values.append([lit(pid), lit(spec_ids[slug])])
    sql.append(insert("programs", program_cols, program_values))
    sql.append(insert("program_specializations", ["program_id", "specialization_id"], link_values))

    intake_values = []
    for i in rows("intakes.csv"):
        if i["program_slug"] not in program_ids:
            errors.append(f"intake: unknown program {i['program_slug']}")
            continue
        intake_values.append([lit(program_ids[i["program_slug"]]), lit(i["season"]), lit(i["academic_year"]),
                              lit(i["application_start"], "date"), lit(i["application_end"], "date")])
    sql.append(insert("program_intakes", ["program_id", "season", "academic_year", "application_start",
                                          "application_end"], intake_values))
    sql.append("refresh materialized view public.mv_admin_stats;\n")

    if errors:
        print("\n".join(errors), file=sys.stderr)
        sys.exit(1)
    OUT.write_text("".join(sql), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(fields)} fields, {len(specs)} specializations, "
          f"{len(unis)} universities, {len(programs)} programs, {len(intake_values)} intakes")


if __name__ == "__main__":
    main()
