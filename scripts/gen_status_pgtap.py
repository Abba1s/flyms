"""Generate supabase/tests/status_parity.test.sql from the shared status vectors.

Keeps the SQL admission_status() function in lockstep with packages/shared/src/status.ts.
Usage: python3 -I scripts/gen_status_pgtap.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VECTORS = ROOT / "packages" / "shared" / "src" / "status-vectors.json"
OUT = ROOT / "supabase" / "tests" / "status_parity.test.sql"


def date(value):
    return "null::date" if value is None else f"'{value}'::date"


def main():
    vectors = json.loads(VECTORS.read_text(encoding="utf-8"))
    lines = [
        "-- Generated by scripts/gen_status_pgtap.py from packages/shared/src/status-vectors.json.",
        "begin;",
        f"select plan({len(vectors)});",
    ]
    for v in vectors:
        name = v["name"].replace("'", "''")
        lines.append(
            f"select is(public.admission_status({date(v['start'])}, {date(v['end'])}, {date(v['today'])}), "
            f"'{v['status']}', '{name}');"
        )
    lines += ["select * from finish();", "rollback;", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} with {len(vectors)} cases")


if __name__ == "__main__":
    main()
